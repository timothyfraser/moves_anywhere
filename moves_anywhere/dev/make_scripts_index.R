# make_scripts_index.R ########################################################
#
# What:      Developer tool: generates docs/README_scripts.md from the script headers.
# Does:      Reads the header block (What, Does, Called by, Reads, Writes, Needs, Exits) of every
#            .R, .sh and .py file in moves_anywhere/scripts/ and writes one Markdown guide: the run
#            step by step (in the order launch.sh runs them), adapters, helpers, tests and tools.
#            Stops with an error if a file is unclassified or a header has no What.
# Called by: Developer tool: run by hand from the repo root; tested by tests/test_scripts_index.sh.
#            Not part of a run; launch.sh does not run it.
# Reads:     moves_anywhere/scripts/*.R, *.sh, *.py (headers only); moves_anywhere/scripts/launch.sh
# Writes:    docs/README_scripts.md (or the path given with --out); LF line endings
# Needs:     base R only. Usage: Rscript moves_anywhere/dev/make_scripts_index.R [--out FILE]
###############################################################################

# Arguments ####################################
args = commandArgs(trailingOnly = TRUE)
out = "docs/README_scripts.md"
if(length(args) >= 2 && args[1] == "--out"){ out = args[2] }

dir_scripts = "moves_anywhere/scripts"
if(!dir.exists(dir_scripts)){ stop("Run from the repo root: ", dir_scripts, " not found") }

# 1. Read one header ####################################
read_header = function(path){
  lines = readLines(path, warn = FALSE)
  lines = sub("\r$", "", lines)
  lines = lines[seq_len(min(length(lines), 40))]
  fields = list()
  current = NULL
  started = FALSE
  for(l in lines){
    if(!started){
      if(grepl("^#!", l)){ next }
      if(grepl("^# .*#{10,}\\s*$", l)){ started = TRUE; next }
      next
    }
    if(grepl("^#{20,}\\s*$", l)){ break }
    if(!grepl("^#", l)){ break }
    txt = trimws(sub("^#'?", "", l))
    if(txt == ""){ current = NULL; next }
    m = regmatches(txt, regexec("^(What|Does|Called by|Reads|Writes|Needs|Exits):\\s*(.*)$", txt))[[1]]
    if(length(m) == 3){
      current = m[2]
      fields[[current]] = m[3]
    } else if(!is.null(current)){
      fields[[current]] = paste(fields[[current]], txt)
    }
  }
  fields
}

# 2. List the code files ####################################
files = list.files(dir_scripts, pattern = "\\.(R|sh|py)$", full.names = FALSE)
files = files[order(files, method = "radix")]
hdr = lapply(files, function(f) read_header(file.path(dir_scripts, f)))
names(hdr) = files
for(f in files){
  if(is.null(hdr[[f]][["What"]]) || !nzchar(hdr[[f]][["What"]])){
    stop("Header of ", f, " has no What field")
  }
}

# 3. Step order from launch.sh ####################################
ls = sub("\r$", "", readLines(file.path(dir_scripts, "launch.sh"), warn = FALSE))
step = NA_integer_
steps = data.frame(script = character(0), step = integer(0), stringsAsFactors = FALSE)
for(l in ls){
  m = regmatches(l, regexec("^# ([0-9]+)\\. ", l))[[1]]
  if(length(m) == 2){ step = as.integer(m[2]); next }
  if(is.na(step) || grepl("^\\s*#", l)){ next }
  hits = regmatches(l, gregexpr("scripts/[A-Za-z0-9_]+\\.(R|sh|py)", l))[[1]]
  for(h in sub("^scripts/", "", hits)){
    if(h %in% files && !(h %in% steps$script)){
      steps = rbind(steps, data.frame(script = h, step = step, stringsAsFactors = FALSE))
    }
  }
}

# 4. Classify: every file exactly once ####################################
# Run: named in launch.sh after a step banner. Adapters: adapt_*. Tests and tools: test_*, validate_*,
# or Called by starts "Developer tool". Legacy: Called by starts "Not used by v3". Helpers and libraries: everything else.
class_of = function(f){
  cb = hdr[[f]][["Called by"]]
  if(is.null(cb)){ cb = "" }
  if(f %in% steps$script || f == "launch.sh"){ return("run") }
  if(grepl("^adapt_", f)){ return("adapt") }
  if(grepl("^Not used by v3", cb)){ return("legacy") }
  if(grepl("^(test_|validate_)", f) || grepl("^Developer tool", cb)){ return("tools") }
  "helper"
}
cls = vapply(files, class_of, character(1))

# 5. Markdown helpers ####################################
cell = function(x){
  if(is.null(x) || is.na(x) || !nzchar(x)){ return("") }
  x = gsub("\\s+", " ", x)
  gsub("|", "\\|", x, fixed = TRUE)
}
fld = function(f, k){ cell(hdr[[f]][[k]]) }
what_does = function(f){
  w = trimws(hdr[[f]][["What"]])
  if(!grepl("[.!?:;]$", w)){ w = paste0(w, ".") }
  cell(paste(w, hdr[[f]][["Does"]]))
}
row_ = function(...){ paste0("| ", paste(c(...), collapse = " | "), " |") }
table_ = function(fs){
  r = c(row_("Script", "What it does", "Called by", "Reads", "Writes"), row_(rep("---", 5)))
  for(f in fs){
    r = c(r, row_(paste0("`", f, "`"), what_does(f), fld(f, "Called by"),
                  fld(f, "Reads"), fld(f, "Writes")))
  }
  r
}

# 6. Build the document ####################################
doc = c("# Scripts guide", "",
  "Part of the MOVES Anywhere guides: see the [index](README.md).", "",
  paste0("Generated by moves_anywhere/dev/make_scripts_index.R from the script headers. ",
         "Do not edit by hand: edit the header in the script, then re-run."), "",
  paste0("This guide lists ", length(files), " scripts in `moves_anywhere/scripts/`."), "",
  "## The run, step by step", "",
  "`launch.sh` is the entry point; the steps below are in the order it runs them.", "",
  row_("Step", "Script", "What it does", "Reads", "Writes"), row_(rep("---", 5)))
doc = c(doc, row_("all", "`launch.sh`", what_does("launch.sh"), fld("launch.sh", "Reads"), fld("launch.sh", "Writes")))
for(i in seq_len(nrow(steps))){
  f = steps$script[i]
  doc = c(doc, row_(steps$step[i], paste0("`", f, "`"), what_does(f),
                    fld(f, "Reads"), fld(f, "Writes")))
}
sec = function(title, key, intro){
  fs = files[cls == key]
  c("", paste0("## ", title), "", intro, "", table_(fs))
}
doc = c(doc,
  sec("Adapters", "adapt", "Scripts named `adapt_*`: each adapts one group of MOVES input tables. `task_adapt.R` runs them in step 6."),
  sec("Helpers and libraries", "helper", "Scripts and files that other scripts call or source."),
  sec("Tests and tools", "tools", "Test scripts, validation scripts and developer tools. A run does not use them."),
  sec("Legacy (v2, not used by v3)", "legacy", "Kept for reference. The v3 run does not call these."))
ex = hdr[["launch.sh"]][["Exits"]]
if(is.null(ex)){ stop("launch.sh header has no Exits field") }
doc = c(doc, "", "## Failure behaviour", "", cell(ex), "", "---", "",
  "Back to the [index](README.md). Next: [The run manifest](RUN_MANIFEST.md).", "")

# 7. Count check ####################################
n_run = sum(cls == "run"); n_other = sum(cls != "run")
counted = n_run + sum(cls == "adapt") + sum(cls == "helper") + sum(cls == "tools") + sum(cls == "legacy")
if(counted != length(files) || any(is.na(cls))){
  stop("Count check failed: ", counted, " classified of ", length(files), " files")
}
con = file(out, "wb")
writeBin(charToRaw(paste0(paste(doc, collapse = "\n"), "\n")), con)
close(con)
cat(sprintf("Wrote %s: %d scripts = %d run + %d adapters + %d helpers + %d tests and tools + %d legacy\n",
            out, length(files), n_run, sum(cls == "adapt"), sum(cls == "helper"), sum(cls == "tools"), sum(cls == "legacy")))
